package com.example.model

import java.util.Locale

/**
 * Domain models and UI states for Task 3D: Category-Specific Plain-Language Medical Explanations.
 *
 * Every explanation model binds directly to immutable Task 3C extracted objects so original
 * values, units, reference ranges, flags, dates, FindingStatus, and FieldProvenance can never
 * be modified or fabricated by AI output.
 */
enum class SupportedExplanationLanguage(
  val code: String,
  val canonicalName: String
) {
  ENGLISH(code = "en", canonicalName = "English"),
  HINDI(code = "hi", canonicalName = "Hindi"),
  BENGALI(code = "bn", canonicalName = "Bengali"),
  MARATHI(code = "mr", canonicalName = "Marathi");

  companion object {
    val launchLanguages: List<SupportedExplanationLanguage> = entries

    fun fromCodeOrName(value: String?): SupportedExplanationLanguage? {
      val normalized = value?.trim()?.lowercase(Locale.ROOT)?.takeIf { it.isNotEmpty() }
        ?: return null
      return entries.firstOrNull { entry ->
        entry.code == normalized || entry.canonicalName.lowercase(Locale.ROOT) == normalized
      }
    }
  }
}

object ExplanationConstants {
  const val DEFAULT_EXPLANATION_LANGUAGE = "English"

  val SUPPORTED_LANGUAGE_CODES: Set<String> =
    SupportedExplanationLanguage.launchLanguages.mapTo(linkedSetOf()) { it.code }

  val SUPPORTED_LANGUAGE_NAMES: List<String> =
    SupportedExplanationLanguage.launchLanguages.map { it.canonicalName }

  /**
   * Resolves requested language code or canonical display name to one of the four approved
   * launch languages (English, Hindi, Bengali, Marathi). Unsupported, planned, blank, null,
   * or invalid inputs safely fall back to English without mapping to another Indian language.
   */
  fun resolveSafeExplanationLanguage(requestedLanguage: String?): String =
    SupportedExplanationLanguage.fromCodeOrName(requestedLanguage)?.canonicalName
      ?: DEFAULT_EXPLANATION_LANGUAGE

  const val MEDICAL_EXPLANATION_DISCLAIMER =
    "AI-Generated Explanation (Not Medically Verified): This plain-language summary is " +
      "generated by AI from your extracted report text for informational clarity only. " +
      "It is not a medical diagnosis, treatment recommendation, or clinical alert. " +
      "Always review your original report with a qualified doctor."

  const val MEDICATION_SAFETY_NOTE =
    "Follow only the dose and schedule printed on your prescription. Never change or stop " +
      "this medication without consulting your doctor."
}

data class MedicalTermDefinition(
  val term: String,
  val simpleDefinition: String
)

// ============================================================================
// 1. LABORATORY EXPLANATION
// ============================================================================

data class ExplainedLabItem(
  val sourceItem: ExtractedLabItem,
  val whatItMeasures: String? = null,
  val plainLanguageExplanation: String? = null,
  val uncertaintyNote: String? = null
)

// ============================================================================
// 2. RADIOLOGY EXPLANATION (Written Report Text Only)
// ============================================================================

data class ExplainedRadiologyFinding(
  val sourceFinding: AnatomicalFinding,
  val plainLanguageExplanation: String? = null,
  val uncertaintyNote: String? = null
)

data class ExplainedRadiologyImpression(
  val sourceImpression: RadiologyImpression,
  val plainLanguageExplanation: String? = null,
  val uncertaintyNote: String? = null
)

// ============================================================================
// 3. CARDIOLOGY EXPLANATION (Written Report Text Only)
// ============================================================================

data class ExplainedCardiologyMetric(
  val fieldKey: String,
  val label: String,
  val originalValue: String,
  val plainLanguageExplanation: String? = null,
  val provenance: FieldProvenance
)

// ============================================================================
// 4. SPECIALISED PATHOLOGY / HISTOPATHOLOGY / ONCOLOGY EXPLANATION
// ============================================================================

data class ExplainedSpecialisedSection(
  val fieldKey: String,
  val sectionTitle: String,
  val originalText: String,
  val plainLanguageExplanation: String? = null,
  val provenance: FieldProvenance
)

// ============================================================================
// 5. CLINICAL DOCUMENT EXPLANATION
// ============================================================================

data class ExplainedClinicalFact(
  val sourceFact: ExtractedClinicalFact,
  val plainLanguageExplanation: String? = null
)

/**
 * Medication explanation restricted strictly to schedule/instructions explicitly printed
 * in [sourceMedication]. Does not infer why a drug was prescribed or suggest dosage changes.
 */
data class ExplainedMedication(
  val sourceMedication: ExtractedMedication,
  val printedScheduleExplanation: String? = null,
  val safetyNote: String = ExplanationConstants.MEDICATION_SAFETY_NOTE
)

// ============================================================================
// UNIFIED CATEGORY-SPECIFIC EXPLANATION RESULT
// ============================================================================

sealed class CategoryExplanation {
  data class Laboratory(
    val labFacilityName: String?,
    val collectionDate: String?,
    val reportDate: String?,
    val items: List<ExplainedLabItem>
  ) : CategoryExplanation()

  data class Radiology(
    val modality: String?,
    val anatomicalRegion: String?,
    val clinicalIndication: String?,
    val techniqueDescription: String?,
    val studyOverviewExplanation: String?,
    val findings: List<ExplainedRadiologyFinding>,
    val impressions: List<ExplainedRadiologyImpression>
  ) : CategoryExplanation()

  data class Cardiology(
    val sourceReport: ExtractedCardiologyReport,
    val modalityExplanation: String?,
    val metrics: List<ExplainedCardiologyMetric>,
    val conclusionExplanation: String?,
    val uncertaintyNote: String?
  ) : CategoryExplanation()

  data class Specialised(
    val sourceReport: ExtractedSpecialisedReport,
    val reportOverviewExplanation: String?,
    val sections: List<ExplainedSpecialisedSection>,
    val conclusionExplanation: String?,
    val uncertaintyNote: String?
  ) : CategoryExplanation()

  data class Clinical(
    val documentSubtype: String?,
    val facilityOrDoctorName: String?,
    val followUpDate: String?,
    val documentOverviewExplanation: String?,
    val diagnoses: List<ExplainedClinicalFact>,
    val procedures: List<ExplainedClinicalFact>,
    val medications: List<ExplainedMedication>,
    val allergies: List<ExplainedClinicalFact>,
    val dischargeInstructions: List<ExplainedClinicalFact>
  ) : CategoryExplanation()
}

data class ReportExplanationResult(
  val category: MedicalDocumentCategory,
  val language: String = ExplanationConstants.DEFAULT_EXPLANATION_LANGUAGE,
  val conciseSummary: String,
  val categoryExplanation: CategoryExplanation,
  val medicalTerms: List<MedicalTermDefinition> = emptyList(),
  val questionsForDoctor: List<String> = emptyList(),
  val uncertaintyNotes: List<String> = emptyList(),
  val safetyDisclaimer: String = ExplanationConstants.MEDICAL_EXPLANATION_DISCLAIMER,
  val generatedTimestamp: Long = System.currentTimeMillis()
)

sealed class ReportExplanationState {
  object Idle : ReportExplanationState()
  object WaitingForConsent : ReportExplanationState()
  object Loading : ReportExplanationState()
  data class Success(val explanation: ReportExplanationResult) : ReportExplanationState()
  data class Error(val message: String, val isRetryable: Boolean = true) : ReportExplanationState()
}
