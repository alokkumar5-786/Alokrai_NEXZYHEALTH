  @Test
  fun `parser returns domain errors for not_a_health_policy and unreadable responses`() {
    val notPolicy = HealthPolicyParser.parseResponse("""{"error":"not_a_health_policy"}""", "hi")
    assertEquals(PolicyParseOutcome.DomainError(PolicyErrorType.NOT_A_HEALTH_POLICY), notPolicy)

    val unreadable = HealthPolicyParser.parseResponse("""{"error":"unreadable"}""", "mr")
    assertEquals(PolicyParseOutcome.DomainError(PolicyErrorType.UNREADABLE), unreadable)
  }

  @Test
  fun `viewModel enforces max 3 files and size limit and zeroes memory on delete`() {
    val fileBytes = "sample policy pdf bytes".toByteArray()
    val fakeReader = object : PolicyFileReader {
      override suspend fun readFile(uri: Uri): FileReadOutcome {
        val name = uri.lastPathSegment ?: "doc.pdf"
        if (name == "huge.pdf") {
          return FileReadOutcome.Error(PolicyErrorType.FILE_TOO_LARGE)
        }
        return FileReadOutcome.Success(
          PolicyFileAttachment(
            id = "id-$name",
            fileName = name,
            mimeType = "application/pdf",
            byteCount = fileBytes.size.toLong(),
            bytes = fileBytes.copyOf()
          )
        )
      }
    }
    val fakeExplainer = object : HealthPolicyExplainerContract {
      override suspend fun explainPolicy(
        attachments: List<PolicyFileAttachment>,
        pastedText: String,
        languageCode: String
      ): PolicyAnalysisOutcome = PolicyAnalysisOutcome.Success(sampleExplanation(languageCode))
    }

    val vm = HealthPolicyViewModel(application, fakeExplainer, fakeReader)
    vm.startFlow("en")
    assertEquals(HealthPolicyStep.LANGUAGE_SELECTION, vm.uiState.value.currentStep)

    vm.confirmLanguageAndProceed()
    assertEquals(HealthPolicyStep.UPLOAD_OR_PASTE, vm.uiState.value.currentStep)

    // Pick 4 files at once -> capped at 3 with friendly too-many-files notice
    vm.onFilesSelected(
      listOf(
        Uri.parse("content://test/p1.pdf"),
        Uri.parse("content://test/p2.pdf"),
        Uri.parse("content://test/p3.pdf"),
        Uri.parse("content://test/p4.pdf")
      )
    )
    assertEquals(3, vm.uiState.value.attachments.size)
    assertEquals(PolicyErrorType.TOO_MANY_FILES, vm.uiState.value.errorType)

    val retainedRef = vm.uiState.value.attachments.first()
    vm.onPastedTextChanged("Policy period 1 year")
    vm.analyzePolicy()
    assertEquals(HealthPolicyStep.RESULT, vm.uiState.value.currentStep)
    assertNotNull(vm.uiState.value.explanation)

    // Delete now must zero raw byte array and clear all state
    vm.deleteDocumentAndReset()
    assertArrayEquals(ByteArray(fileBytes.size), retainedRef.bytes)
    assertTrue(vm.uiState.value.attachments.isEmpty())
    assertEquals("", vm.uiState.value.pastedPolicyText)
    assertNull(vm.uiState.value.explanation)
    assertFalse(vm.uiState.value.canAnalyze)

    // Oversized file error before upload
    vm.confirmLanguageAndProceed()
    vm.onFilesSelected(listOf(Uri.parse("content://test/huge.pdf")))
    assertEquals(PolicyErrorType.FILE_TOO_LARGE, vm.uiState.value.errorType)
    assertTrue(vm.uiState.value.attachments.isEmpty())
    assertTrue(AiModelConfig.MAX_RAW_PAYLOAD_BYTES > 0L)
  }

